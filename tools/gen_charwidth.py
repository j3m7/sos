# Generate src/shell/charwidth_table.h, the terminal column widths used by charwidth.c, from the
# Unicode database of the Python running it:
#
#   python3 tools/gen_charwidth.py > src/shell/charwidth_table.h
#
# Two columns: East Asian Wide and Fullwidth (CJK, Hangul syllables, most emoji), plus the
# unassigned parts of planes 2 and 3, which are reserved for CJK. No columns: combining marks
# (Mn, Me), ZWNJ and ZWJ, and the Hangul medial vowels and final consonants (U+1160-U+11FF),
# which join the syllable before them. This is what terminals' wcwidth() does too, give or take
# their Unicode version.

import sys
import unicodedata


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000):
        if pred(cp):
            if start is None:
                start = cp
        elif start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def zero(cp):
    if 0xD800 <= cp <= 0xDFFF:
        return False
    if cp in (0x200C, 0x200D) or 0x1160 <= cp <= 0x11FF:
        return True
    return unicodedata.category(chr(cp)) in ("Mn", "Me")


def wide(cp):
    if 0xD800 <= cp <= 0xDFFF or zero(cp):
        return False
    if 0x20000 <= cp <= 0x2FFFD or 0x30000 <= cp <= 0x3FFFD:
        return True
    return unicodedata.east_asian_width(chr(cp)) in ("W", "F")


def table(name, rs):
    lines = [f"static const charwidth_range_t {name}[] = {{"]
    row = ""
    for a, b in rs:
        item = f"{{0x{a:X}, 0x{b:X}}}, "
        if len(row) + len(item) > 96:
            lines.append("    " + row.rstrip())
            row = ""
        row += item
    if row:
        lines.append("    " + row.rstrip())
    lines.append("};")
    return "\n".join(lines)


def main():
    z, w = ranges(zero), ranges(wide)
    print("// SPDX-License-Identifier: GPL-3.0-or-later")
    print("// Copyright (C) 2026 Julio Martinez")
    print("//")
    print(f"// Generated by tools/gen_charwidth.py from Unicode {unicodedata.unidata_version}. Don't edit.")
    print(f"// {len(z)} zero-width ranges, {len(w)} wide ranges.")
    print()
    print(table("charwidth_zero", z))
    print()
    print(table("charwidth_wide", w))


if __name__ == "__main__":
    sys.exit(main())
