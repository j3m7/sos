# docs/commands.md is generated from the manual pages (man/*.txt), so a command is documented
# once, in its page. For each section of man/index.txt it writes a table with one row per page:
# the command's forms (the page's SYNOPSIS), where it may be used (from the "(console only)" and
# "(change: console only)" marks on the forms) and its one-line description (the NAME line),
# linking to the page. The intro page's text opens the document.
#
#   tools/man-docs.py           write docs/commands.md
#   tools/man-docs.py --check   fail if docs/commands.md isn't what the pages give (a host test)

import os
import re
import sys
import textwrap

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAN = os.path.join(ROOT, "man")
OUT = os.path.join(ROOT, "docs", "commands.md")

HEADER = """# Shell commands

<!-- Generated by tools/man-docs.py from the manual pages in man/: edit a page, not this file. -->

Every command the SOS shell accepts, one row per command, linking to its manual page: the same
text `man <command>` shows on the board ([man/README.md](../man/README.md) says how a page is
written). The *Where* column says whether SSH may run the command: *any*, *console only*, or
*console only to change* (SSH can show the value but not set it); when only some forms are
console only, they are marked in the first column.
"""


def fail(msg):
    print("man-docs: " + msg, file=sys.stderr)
    sys.exit(1)


def read_page(topic):
    path = os.path.join(MAN, topic + ".txt")
    if not os.path.exists(path):
        fail("man/index.txt names '%s' but there is no man/%s.txt" % (topic, topic))
    lines = open(path, encoding="utf-8").read().split("\n")
    sections, current = {}, None
    for line in lines:
        if line and not line.startswith(" "):
            current = line
            sections.setdefault(current, [])
        elif current is not None:
            sections[current].append(line)
    m = re.match(r"    %s - (.+)" % re.escape(topic), lines[1])
    if not m:
        fail("man/%s.txt: line 2 isn't '    %s - <description>'" % (topic, topic))
    desc = m.group(1)
    forms = [l.strip() for l in sections.get("SYNOPSIS", []) if l.strip()]
    return desc, forms, sections


def where(forms):
    """From the marks on the forms: any, console only, console only to change, or mixed."""
    marks = []
    for f in forms:
        if "(change: console only)" in f:
            marks.append("change")
        elif "(console only)" in f:
            marks.append("console")
        else:
            marks.append("any")
    if not marks or all(m == "any" for m in marks):
        return "any"
    if all(m == "console" for m in marks):
        return "console only"
    if all(m == "change" for m in marks):
        return "console only to change"
    return "any (marked forms: console only)"


def form_cell(forms):
    cells = []
    for f in forms:
        f = re.sub(r"\s*\((change: )?console only\)", lambda m: " *(console only%s)*" % (" to change" if m.group(1) else ""), f)
        head, _, tail = f.partition(" *(")
        cells.append("`%s`%s" % (head.strip().replace("|", "\\|"), (" *(" + tail) if tail else ""))
    return "<br>".join(cells) if cells else ""


def intro_prose(sections):
    out = []
    for para in "\n".join(sections.get("DESCRIPTION", [])).split("\n\n"):
        text = " ".join(l.strip() for l in para.split("\n") if l.strip())
        if text:
            out.append(textwrap.fill(text, 99))
    return "\n\n".join(out)


def main():
    check = "--check" in sys.argv[1:]
    index, seen = [], set()
    for line in open(os.path.join(MAN, "index.txt"), encoding="utf-8"):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        name, _, topics = line.partition(":")
        topics = topics.split()
        for t in topics:
            if t in seen:
                fail("man/index.txt lists '%s' twice" % t)
            seen.add(t)
        index.append((name.strip(), topics))
    for f in sorted(os.listdir(MAN)):
        if f.endswith(".txt") and f != "index.txt" and f[:-4] not in seen:
            fail("man/%s isn't in man/index.txt" % f)

    out = [HEADER]
    pages = {t: read_page(t) for _, topics in index for t in topics}
    if "intro" in pages:
        out.append(intro_prose(pages["intro"][2]) + "\n")
    for name, topics in index:
        out.append("## %s\n" % name)
        out.append("| Command | Where | What it does |\n|---|---|---|")
        for t in topics:
            desc, forms, _ = pages[t]
            if t == "intro":
                continue
            cell = form_cell(forms) or "`%s`" % t
            out.append("| %s | %s | %s ([page](../man/%s.txt)) |" % (cell, where(forms), desc.replace("|", "\\|"), t))
        out.append("")
    text = "\n".join(out)
    if check:
        current = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else ""
        if current != text:
            fail("docs/commands.md is out of date: run tools/man-docs.py and commit it")
        print("man-docs: docs/commands.md current (%d pages)" % len(pages))
    else:
        open(OUT, "w", encoding="utf-8").write(text)
        print("docs/commands.md: %d pages in %d sections" % (len(pages), len(index)))


main()
